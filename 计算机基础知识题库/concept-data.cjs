const seen = new Set();
for (const [topic, stem, correct, first, second, third] of conceptChoices) {
  if (!topic || !stem || !correct) throw new Error(`概念选择题不完整：${stem}`);
  if (seen.has(stem)) throw new Error(`概念题干重复：${stem}`);
  const options = [correct, first, second, third];
  if (options.some((item) => typeof item !== "string" || item.trim() === "")) throw new Error(`选项为空：${stem}`);
  if (new Set(options).size !== 4) throw new Error(`选项重复：${stem}`);
  seen.add(stem);
}
for (const [topic, stem, answer] of conceptChoices) {
  const text = String(answer);
  if (text.length > 24) continue;
  const blankStem = `${stem}____。`;
  if (seen.has(blankStem) || blankStem.split("____").length !== 2) continue;
  seen.add(blankStem);
  conceptBlanks.push([topic, blankStem, text]);
}
if (conceptChoices.length < 210 || conceptBlanks.length < 170) {
  throw new Error(`概念题不足：选择${conceptChoices.length}，填空${conceptBlanks.length}`);
}

